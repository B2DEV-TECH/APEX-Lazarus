-- APEX Lazarus demo: tables of the demo application. Installed in both
-- parsing schemas (LZ_DEMO_PRD and LZ_DEMO_DEV) so the two environments start
-- from the same schema. All data is synthetic.

create table lz_departments (
    department_id    number          not null,
    department_name  varchar2(60)    not null,
    constraint lz_departments_pk primary key (department_id)
);

create table lz_employees (
    employee_id      number generated by default as identity,
    first_name       varchar2(40)    not null,
    last_name        varchar2(40)    not null,
    email            varchar2(80)    not null,
    job_title        varchar2(60)    not null,
    department_id    number          not null,
    salary           number(10, 2)   not null,
    hire_date        date            not null,
    constraint lz_employees_pk      primary key (employee_id),
    constraint lz_employees_dept_fk foreign key (department_id)
        references lz_departments (department_id)
);

